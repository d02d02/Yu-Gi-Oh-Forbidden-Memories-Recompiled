#!/usr/bin/env python3
"""Regenerate art_files.h from the textures in artes_duel_links_fm/ (prepare_art.py) (each named
<card id>_<Name>.png): python make_art_table.py  (run from this directory)."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
folder = "artes_duel_links_fm"
rows = []
for name in os.listdir(os.path.join(here, folder)):
    m = re.match(r"(\d+)_.*\.tex$", name, re.I)
    if m:
        rows.append((int(m.group(1)), name))
rows.sort()
with open(os.path.join(here, "art_files.h"), "w", encoding="utf-8", newline="\n") as out:
    out.write("/* Generated by make_art_table.py: card id -> PNG, sorted by id. */\n")
    out.write("typedef struct { int card; const char *file; } ArtFile;\n")
    out.write("static const ArtFile art_files[] = {\n")
    for card, name in rows:
        out.write('    {%d, "%s/%s"},\n' % (card, folder, name.replace("\\", "\\\\").replace('"', '\\"')))
    out.write("};\n")
print(len(rows), "cards")
